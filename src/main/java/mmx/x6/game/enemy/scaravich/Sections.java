    static int roll(World w, int pole) {
        if (pole == 1 && w.rollPhase == 0) {
            w.rollPhase = 1;
            w.routeRow = w.rng.nextInt(12);
        } else if (pole == 3 && w.rollPhase == 1) {
            w.rollPhase = 2;
            w.routeRow = w.rng.nextInt(12);
        }
        return ROUTE[w.routeRow][pole - 1];
    }

    static void placeBlocks(World w, int section) {
        for (int[] b : BLOCKS[section]) {
            if (!w.rng.nextBoolean()) {
                w.copyTiles(b[2], b[3], b[4], b[5], b[0], b[1]);
            }
        }
    }

    static Checkpoint entry(int section) {
        return place(ENTRY[section], true);
    }

    static Checkpoint returnPoint(int cleared) {
        // TODO: the facing after a teleport is not read; the player faces the pole at a return point and right at a section entry (docs/gaps.md, "Scaravich routing")
        return place(RETURN[cleared], cleared == 0 || cleared == 3);
    }

    private static Checkpoint place(int[] e, boolean faceRight) {
        return new Checkpoint(e[0], e[1], e[2], e[3], e[4], e[5], e[6], e[7], faceRight, 1);
    }
